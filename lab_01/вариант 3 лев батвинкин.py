# Вариант 3: Энергия заряженного конденсатора
# Формула: W = (C * U^2) / 2

# Исходные данные (константы)
C = 4.7e-5  # Емкость, Ф
U = 220.0   # Напряжение, В

# Вычисление
W = (C * U**2) / 2

# Вывод результата с округлением до 4 знаков после запятой
print(f"Энергия заряженного конденсатора: {round(W, 4)} Дж")
