import tkinter as tk  # Импортируем базовую библиотеку tkinter для графического интерфейса
from tkinter import ttk, messagebox  # Импортируем современные виджеты (ttk) и всплывающие окна сообщений (messagebox)

class Task:  # Объявляем класс Task для представления задачи
    def __init__(self, name: str, priority: int, duration: int):  # Конструктор класса, принимает имя, приоритет и длительность
        self.name = name  # Записываем переданное имя задачи в атрибут объекта
        self.priority = priority  # Записываем приоритет (автоматически вызывает setter для проверки)
        self.duration = duration  # Записываем переданную длительность задачи в атрибут объекта

    @property  # Объявляем геттер для свойства priority
    def priority(self) -> int:  # Метод для чтения значения приоритета
        return self._priority  # Возвращаем значение защищенной переменной _priority

    @priority.setter  # Объявляем сеттер для свойства priority (реализация инкапсуляции)
    def priority(self, value: int):  # Метод для записи значения приоритета с проверкой
        if not (1 <= value <= 5):  # Проверяем, лежит ли значение вне диапазона от 1 до 5
            raise ValueError("Приоритет задачи должен быть в диапазоне от 1 до 5!")  # Вызываем ошибку, если значение некорректно
        self._priority = value  # Сохраняем корректное значение в защищенный атрибут _priority

    def __str__(self):  # Переопределяем строковое представление объекта (для вывода через print)
        return f"Задача '{self.name}' (Приоритет: {self.priority}, Длительность: {self.duration})"  # Возвращаем строку с описанием

class Robot:  # Объявляем базовый класс Robot для представления стандартного робота
    def __init__(self, name: str):  # Конструктор класса, принимает имя робота
        self.name = name  # Записываем имя робота в атрибут объекта
        self.current_task = None  # Изначально текущая задача отсутствует (робот свободен)

    @property  # Объявляем геттер для свойства status
    def status(self) -> str:  # Метод для получения текстового статуса робота
        if self.current_task:  # Проверяем, назначена ли сейчас роботу какая-либо задача
            return f"Занят ({self.current_task.name})"  # Если задача есть, возвращаем статус "Занят" с ее именем
        return "Свободен"  # Если задачи нет, возвращаем статус "Свободен"

    def can_take_task(self, task: Task) -> bool:  # Метод для проверки, может ли робот взять данную задачу
        return self.current_task is None  # Возвращаем True, если робот свободен, иначе False

    def assign_task(self, task: Task):  # Метод для назначения задачи роботу
        if not self.can_take_task(task):  # Проверяем через метод, доступен ли робот для этой задачи
            raise ValueError(f"Робот {self.name} не может взять эту задачу!")  # Вызываем ошибку, если робот не может ее взять
        self.current_task = task  # Записываем переданную задачу в качестве текущей

    def __str__(self):  # Переопределяем строковое представление объекта робота
        return f"Робот {self.name} -> Статус: {self.status}"  # Возвращаем строку с именем робота и его статусом

class TransportRobot(Robot):  # Объявляем класс-потомок TransportRobot, наследующий базовый класс Robot
    def __init__(self, name: str, max_payload: float = 50.0):  # Конструктор класса, принимает имя и грузоподъемность
        super().__init__(name)  # Вызываем конструктор родительского класса Robot для инициализации имени
        self.max_payload = max_payload  # Записываем уникальный атрибут грузоподъемности для транспортного робота

    def can_take_task(self, task: Task) -> bool:  # Переопределяем метод проверки возможности взять задачу (полиморфизм)
        if self.current_task is not None:  # Проверяем базовое условие: если робот уже занят
            return False  # Сразу возвращаем False, так как занятый робот не берет новые задачи
        transport_keywords = ["доставка", "перевозка", "склад", "груз", "транспортировка"]  # Ключевые слова для фильтрации
        task_name_lower = task.name.lower()  # Приводим название задачи к нижнему регистру для корректного поиска
        return any(keyword in task_name_lower for keyword in transport_keywords)  # Проверяем наличие ключевых слов в имени задачи

    def __str__(self):  # Переопределяем строковое представление объекта транспортного робота
        base_str = super().__str__()  # Получаем стандартную строковую информацию из родительского класса
        return f"[Транспорт] {base_str} (Грузоподъемность: {self.max_payload} кг)"  # Возвращаем строку с добавлением спец. данных

class DispatcherApp(tk.Tk):  # Объявляем главный класс графического приложения, наследующий окно tk.Tk
    def __init__(self, robots_list: list):  # Конструктор класса окна, принимает список доступных роботов
        super().__init__()  # Инициализируем базовый класс окна tkinter
        self.title("Диспетчер задач роботов")  # Устанавливаем текстовый заголовок главного окна
        self.geometry("750x500")  # Задаем фиксированные размеры графического окна (ширина и высота)
        self.resizable(False, False)  # Запрещаем изменение размеров окна пользователем
        self.robots = robots_list  # Сохраняем переданный список роботов в атрибут приложения
        self.tasks_pool = []  # Создаем пустой список для хранения очереди нераспределенных задач
        self._build_widgets()  # Вызываем внутренний метод для создания и размещения виджетов на экране
        self._update_robots_view()  # Вызываем метод для вывода актуальной информации о роботах в интерфейс

    def _build_widgets(self):  # Внутренний метод для сборки и разметки графических элементов (виджетов)
        form_frame = ttk.LabelFrame(self, text=" Добавление новой задачи ")  # Создаем рамку-группу для формы ввода
        form_frame.grid(row=0, column=0, padx=10, pady=10, sticky="nsew")  # Размещаем форму ввода в левой ячейке сетки графического окна

        ttk.Label(form_frame, text="Название задачи:").pack(anchor="w", padx=5, pady=2)  # Создаем и размещаем текстовую метку названия
        self.entry_name = ttk.Entry(form_frame, width=25)  # Создаем поле ввода для названия задачи
        self.entry_name.pack(fill="x", padx=5, pady=2)  # Размещаем поле ввода и растягиваем по горизонтали
        self.entry_name.insert(0, "Доставка деталей")  # Устанавливаем значение по умолчанию в поле названия

        ttk.Label(form_frame, text="Приоритет (1-5):").pack(anchor="w", padx=5, pady=2)  # Создаем и размещаем текстовую метку приоритета
        self.combo_priority = ttk.Combobox(form_frame, values=["1", "2", "3", "4", "5"], state="readonly")  # Создаем выпадающий список
        self.combo_priority.current(2)  # Устанавливаем текущий выбор на значение "3" (индекс 2)
        self.combo_priority.pack(fill="x", padx=5, pady=2)  # Размещаем выпадающий список в форме

        ttk.Label(form_frame, text="Длительность (ед.):").pack(anchor="w", padx=5, pady=2)  # Создаем и размещаем текстовую метку длительности
        self.entry_duration = ttk.Entry(form_frame, width=25)  # Создаем поле ввода для длительности задачи
        self.entry_duration.pack(fill="x", padx=5, pady=2)  # Размещаем поле ввода на форме
        self.entry_duration.insert(0, "10")  # Устанавливаем значение по умолчанию в поле длительности

        ttk.Button(form_frame, text="Создать задачу", command=self._on_add_task).pack(fill="x", padx=5, pady=10)  # Кнопка создания задачи
        ttk.Button(form_frame, text="Назначить свободным роботам", command=self._on_dispatch).pack(fill="x", padx=5, pady=2)  # Кнопка диспетчеризации

        table_frame = ttk.LabelFrame(self, text=" Текущая очередь задач ")  # Создаем рамку-группу для таблицы очереди задач
        table_frame.grid(row=0, column=1, padx=10, pady=10, sticky="nsew")  # Размещаем рамку таблицы в правой ячейке сетки окна

        self.tree = ttk.Treeview(table_frame, columns=("name", "priority", "duration"), show="headings", height=8)  # Создаем виджет таблицы
        self.tree.heading("name", text="Название")  # Настраиваем заголовок столбца названия задачи
        self.tree.heading("priority", text="Приоритет")  # Настраиваем заголовок столбца приоритета задачи
        self.tree.heading("duration", text="Длительность")  # Настраиваем заголовок столбца длительности задачи
        self.tree.column("name", width=180)  # Задаем ширину столбца названия задачи в пикселях
        self.tree.column("priority", width=90, anchor="center")  # Задаем ширину и выравнивание по центру для столбца приоритета
        self.tree.column("duration", width=100, anchor="center")  # Задаем ширину и выравнивание по центру для столбца длительности
        self.tree.pack(fill="both", expand=True, padx=5, pady=5)  # Размещаем таблицу внутри своей рамки, растягивая на всю площадь

        bottom_frame = ttk.LabelFrame(self, text=" Мониторинг роботов и Журнал событий ")  # Создаем нижнюю рамку-группу для статусов и логов
        bottom_frame.grid(row=1, column=0, columnspan=2, padx=10, pady=5, sticky="nsew")  # Размещаем рамку на всю ширину нижней части окна

        self.robots_text = tk.Text(bottom_frame, width=38, height=10, font=("Consolas", 10), bg="#f8f9fa")  # Поле вывода статуса роботов
        self.robots_text.pack(side="left", padx=5, pady=5, fill="y")  # Размещаем поле статусов слева в нижней панели

        self.log_text = tk.Text(bottom_frame, width=54, height=10, font=("Consolas", 10), bg="#f0f4f8")  # Поле вывода лога событий диспетчера
        self.log_text.pack(side="right", padx=5, pady=5, fill="both", expand=True)  # Размещаем поле логов справа, растягивая его

        self._log("Система запущена. Диспетчер готов к работе.")  # Добавляем в журнал стартовую запись о готовности системы

    def _log(self, message: str):  # Внутренний метод для запись текстовых сообщений в правое поле журнала событий
        self.log_text.insert(tk.END, f">> {message}\n")  # Вставляем переданное сообщение в самый конец текстового поля
        self.log_text.see(tk.END)  # Автоматически прокручиваем текстовое поле к последней добавленной строке

    def _update_robots_view(self):  # Внутренний метод для обновления текстовой информации о состоянии роботов
        self.robots_text.delete("1.0", tk.END)  # Очищаем все текстовое поле с первой строки до самого конца
        self.robots_text.insert(tk.END, "СТАТУС ИСПОЛНИТЕЛЕЙ:\n")  # Пишем заголовок в текстовом поле
        self.robots_text.insert(tk.END, "=" * 35 + "\n")  # Добавляем декоративную разделительную линию
        for r in self.robots:  # Обходим циклом каждого робота из сохраненного списка системы
            self.robots_text.insert(tk.END, f"{r}\n\n")  # Добавляем строковое описание робота в текстовое поле

    def _update_tasks_table(self):  # Внутренний метод для синхронизации графической таблицы Treeview с пулом задач в коде
        for item in self.tree.get_children():  # Обходим все элементы (строки), которые сейчас присутствуют в таблице
            self.tree.delete(item)  # Удаляем каждую визуальную строку из виджета таблицы
        for task in self.tasks_pool:  # Обходим каждую задачу из актуального пула задач в памяти программы
            self.tree.insert("", tk.END, values=(task.name, task.priority, task.duration))  # Вставляем строку с данными задачи в конец таблицы

    def _on_add_task(self):  # Метод-обработчик события нажатия кнопки "Создать задачу"
        try:  # Начинаем защищенный блок обработки исключений для валидации ввода пользователя
            name = self.entry_name.get().strip()  # Получаем строку названия из поля ввода и удаляем пробелы по краям
            if not name:  # Проверяем условие, если поле ввода имени оказалось пустым
                raise ValueError("Название задачи не может быть пустым!")  # Генерируем ошибку с описанием проблемы
            priority = int(self.combo_priority.get())  # Получаем выбранный приоритет и конвертируем его в тип int
            duration = int(self.entry_duration.get().strip())  # Получаем длительность из поля ввода и конвертируем в тип int
            if duration <= 0:  # Проверяем условие, если длительность работы неположительная
                raise ValueError("Длительность работы должна быть больше 0!")  # Генерируем ошибку с описанием проблемы

            new_task = Task(name, priority, duration)  # Инстанцируем объект задачи (здесь сработает валидация внутри Task)
            self.tasks_pool.append(new_task)  # Добавляем успешно созданный объект задачи в общий пул очереди
            self.tasks_pool.sort(key=lambda t: t.priority, reverse=True)  # Сортируем список задач в пуле по убыванию приоритета
            self._update_tasks_table()  # Обновляем графическое отображение таблицы задач на экране
            self._log(f"Добавлена задача: {new_task.name} (P:{priority})")  # Пишем информационное сообщение в журнал событий
            self.entry_name.delete(0, tk.END)  # Очищаем поле ввода названия задачи для последующего ввода
        except ValueError as err:  # Перехватываем исключение ValueError при некорректных данных ввода
            messagebox.showerror("Ошибка валидации", f"Некорректный ввод:\n{err}")  # Отображаем всплывающее диалоговое окно с ошибкой

    def _on_dispatch(self):  # Метод-обработчик события нажатия кнопки "Назначить свободным роботам"
        if not self.tasks_pool:  # Проверяем условие, если пул задач пуст
            messagebox.showinfo("Инфо", "Очередь задач пуста!")  # Показываем информационное окно, что распределять нечего
            return  # Завершаем выполнение метода распределения задач
        assigned_any = False  # Локальный флаг для фиксации того, произошло ли хоть одно успешное назначение задачи
        remaining_tasks = list(self.tasks_pool)  # Создаем копию списка пула задач для безопасного удаления элементов в цикле
        for task in remaining_tasks:  # Итерируемся по каждой задаче из очереди (начиная с высшего приоритета после сортировки)
            for robot in self.robots:  # Итерируемся по списку всех роботов, зарегистрированных в системе диспетчера
                if robot.can_take_task(task):  # Проверяем полиморфным методом, подходит ли данная задача этому роботу
                    robot.assign_task(task)  # Вызываем метод назначения задачи выбранному роботу (меняем его внутреннее состояние)
                    self.tasks_pool.remove(task)  # Удаляем назначенную задачу из пула нераспределенных задач в памяти
                    self._log(f"Успех: Роботу '{robot.name}' поручена задача '{task.name}'")  # Пишем успешное действие в лог событий
                    assigned_any = True  # Меняем флаг назначения на True (в интерфейсе есть изменения)
                    break  # Прерываем цикл поиска робота для текущей задачи и переходим к следующей задаче в очереди
        if assigned_any:  # Проверяем, изменилось ли состояние распределения в очереди задач
            self._update_tasks_table()  # Перерисовываем графическую таблицу очереди задач на экране
            self._update_robots_view()  # Перерисовываем графический список мониторинга роботов (их новые статусы)
        else:  # Если цикл завершился, но ни одна задача не была распределена роботам
            self._log("Внимание: Ни один робот не смог взять задачи из очереди.")  # Пишем предупреждающее сообщение в журнал событий

def main():  # Главная функция для инициализации компонентов и запуска приложения
    fleet = [  # Создаем список (парк) объектов различных роботов мехатронной системы
        Robot(name="Universal-01"),  # Добавляем в список первый объект базового класса Robot
        TransportRobot(name="Transporter-Heavy", max_payload=150.0),  # Добавляем объект специализированного класса TransportRobot
        Robot(name="Universal-02"),  # Добавляем в список второй объект базового класса Robot
        TransportRobot(name="AGV-Sklad", max_payload=40.0)  # Добавляем второй объект класса TransportRobot со своими параметрами
    ]  # Завершаем формирование списка исполнителей мехатронного объекта
    app = DispatcherApp(robots_list=fleet)  # Создаем объект приложения графического интерфейса, передавая ему список роботов
    app.mainloop()  # Запускаем главный бесконечный цикл обработки событий tkinter для отображения окна

if __name__ == "__main__":  # Проверяем конструкцию, запущен ли данный скрипт непосредственно как главный файл программы
    main()  # Вызываем главную точку входа main() для старта выполнения приложения
